def translate_html(html: str, language: str) -> str:
    if language != "fr":
        return html
    protected: list[str] = []

    def protect_attribute(match: re.Match[str]) -> str:
        protected.append(match.group(0))
        return f"__I18N_ATTRIBUTE_{len(protected) - 1}__"

    # Preserve form values, selectors and URLs while translating visible labels.
    html = re.sub(
        r"\b(?:value|name|type|href|action|class|id|for|data-[\w-]+)=(?:\"[^\"]*\"|'[^']*')",
        protect_attribute,
        html,
    )
    pattern = re.compile(
        "|".join(re.escape(key) for key in sorted(TRANSLATIONS, key=len, reverse=True))
    )
    translated = pattern.sub(lambda match: TRANSLATIONS[match.group(0)], html)
    translated = re.sub(
        r"Affichage de (\d+)-(\d+) de (\d+) enregistrements",
        r"Affichage de \1 à \2 sur \3 enregistrements",
        translated,
    )
    translated = re.sub(
        r"Page (\d+) de (\d+)",
        r"Page \1 sur \2",
        translated,
    )
    for index, attribute in enumerate(protected):
        translated = translated.replace(f"__I18N_ATTRIBUTE_{index}__", attribute)
    return translated
